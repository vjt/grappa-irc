defmodule Grappa.E2eRequests.Request do
  @moduledoc """
  Schema for `e2e_requests` — one request to start an end-to-end encrypted
  chat between a subject and a peer on a network, whichever side asked
  (issue 2486).

  `peer` is the RAW nick, for display and the wire; the KEY is its ASCII
  fold, on a UNIQUE expression index per subject and network, like
  `query_windows.target_nick`. `state` is the stored closed set
  (`t:state/0`): `incoming` (the peer asked us), `outgoing` (we asked the
  peer), `accepted` and `refused` (the peer's answer to our asking, kept
  until a client has shown it). `expired` is derived, never stored
  (`Grappa.E2eRequests.expired?/2`).

  `updated_at` is the instant the row entered its state. For a pending row
  that is when the REQUEST went out or arrived, which is what the 24 h
  deadline counts from, so it is written explicitly on every transition
  (a re-ask that changes nothing else still restarts the clock). `payload`
  is the peer's latest, opaque: grappa checks its characters and size and
  never parses it. `peer_device` is the `from` of the peer's latest consent
  line on the row, a device id or `*` (their grappa answering for them), and
  `nil` once we ask afresh: where a REFUSE goes when the user says no with
  no device of its own (vjt's ruling R2). On an `incoming` row it is always
  a device id, since only a device sends a REQUEST. Never on the wire.

  Exactly one of `:user_id` / `:visitor_id` is set, enforced by
  `Grappa.Subject.validate_xor/1` and the `e2e_requests_subject_xor` CHECK,
  like every other per-subject table. Public API lives in
  `Grappa.E2eRequests`.
  """
  use Ecto.Schema
  import Ecto.Changeset

  alias Grappa.Accounts.User
  alias Grappa.IRC.{E2e, Identifier}
  alias Grappa.Networks.Network
  alias Grappa.Subject
  alias Grappa.Visitors.Visitor

  @states [:incoming, :outgoing, :accepted, :refused]

  @max_payload_bytes 1024

  @typedoc "The stored states. `expired` is derived on the wire, never stored."
  @type state :: :incoming | :outgoing | :accepted | :refused

  @type t :: %__MODULE__{
          id: pos_integer() | nil,
          user_id: Ecto.UUID.t() | nil,
          user: User.t() | Ecto.Association.NotLoaded.t() | nil,
          visitor_id: Ecto.UUID.t() | nil,
          visitor: Visitor.t() | Ecto.Association.NotLoaded.t() | nil,
          network_id: integer() | nil,
          network: Network.t() | Ecto.Association.NotLoaded.t() | nil,
          peer: String.t() | nil,
          state: state() | nil,
          payload: String.t() | nil,
          peer_device: E2e.address() | nil,
          inserted_at: DateTime.t() | nil,
          updated_at: DateTime.t() | nil
        }

  schema "e2e_requests" do
    belongs_to :user, User, type: :binary_id
    belongs_to :visitor, Visitor, type: :binary_id
    belongs_to :network, Network

    field :peer, :string
    field :state, Ecto.Enum, values: @states
    field :payload, :string
    field :peer_device, :string

    # Written by the context on every transition, never autogenerated:
    # the deadline counts from `updated_at`, and a re-ask that changes no
    # other column must still move it.
    field :inserted_at, :utc_datetime
    field :updated_at, :utc_datetime
  end

  @doc "The stored states."
  @spec states() :: [state(), ...]
  def states, do: @states

  @doc "The most bytes a payload may hold: a consent line carries a key hint, not a message."
  @spec max_payload_bytes() :: 1024
  def max_payload_bytes, do: @max_payload_bytes

  @doc """
  Builds an insert or update changeset. `peer` must be a nick, `state` one
  of `states/0`, `payload` (nullable) compact JSON text
  (`Grappa.IRC.E2e.chunk?/1`) of at most `max_payload_bytes/0`,
  `peer_device` (nullable) a device id or `*`.
  """
  @spec changeset(t(), map()) :: Ecto.Changeset.t()
  def changeset(request, attrs) do
    request
    |> cast(attrs, [
      :user_id,
      :visitor_id,
      :network_id,
      :peer,
      :state,
      :payload,
      :peer_device,
      :inserted_at,
      :updated_at
    ])
    |> validate_required([:network_id, :peer, :state, :inserted_at, :updated_at])
    |> validate_change(:peer, fn :peer, peer ->
      # Issue 2599 — the peer's nick is the upstream's call.
      if Identifier.wire_nick?(peer), do: [], else: [peer: "is not a nick"]
    end)
    |> validate_change(:payload, fn :payload, payload ->
      if E2e.chunk?(payload), do: [], else: [payload: "is not compact JSON text"]
    end)
    |> validate_length(:payload, max: @max_payload_bytes, count: :bytes)
    |> validate_change(:peer_device, fn :peer_device, device ->
      if device == "*" or E2e.did?(device), do: [], else: [peer_device: "is not a device id or *"]
    end)
    |> Subject.validate_xor()
    |> assoc_constraint(:user)
    |> assoc_constraint(:visitor)
    |> assoc_constraint(:network)
    |> check_constraint(:subject,
      name: :e2e_requests_subject_xor,
      message: "user_id and visitor_id are mutually exclusive"
    )
  end
end
